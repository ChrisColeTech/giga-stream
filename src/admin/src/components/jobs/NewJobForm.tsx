import { Plus } from "lucide-react";
import { Input } from "@giga/ui/controls/Input";
import { Toggle } from "@giga/ui/controls/Toggle";
import { FIELD_CONTROL } from "@giga/ui/form/form-classes";
import { Row } from "@giga/ui/form/Row";
import { NewRecordGroup } from "@/components/records/NewRecordGroup";
import { SAVING_REASON, UNREACHABLE_REASON } from "@/constants/account-copy";
import { CATALOG_TYPE, ENABLED_TIP, NAME_TIP, TYPE_FIXED_TIP } from "@/constants/job-copy";
import { useJobActions } from "@/hooks/useJobActions";
import { useRecordForm } from "@/hooks/useRecordForm";
import { createReason } from "@/lib/job-checks";
import { EMPTY_NEW_JOB, sameNewJob } from "@/lib/job-draft";
import { useAppStore } from "@/store/app-store";
import { CatalogRows } from "./CatalogRows";
import { JobScheduleRows } from "./JobScheduleRows";

/** New catalog job: the same identity, catalog config, enabled state and schedule controls as edit. Playlist jobs are
 *  generated by playlist imports and cannot be created here. */
export function NewJobForm() {
  const form = useRecordForm({ initial: EMPTY_NEW_JOB, same: sameNewJob });
  const { flows, saving, track } = useJobActions();
  const unreachable = useAppStore((state) => state.jobs.unreachable);
  const reason = createReason(form.draft, saving ? SAVING_REASON : unreachable ? UNREACHABLE_REASON : undefined);

  const create = async (): Promise<void> => {
    if (reason !== undefined) return;
    form.clearErrors();
    const result = await track("create", () => flows.create(form.draft));
    if (result.ok) form.reset(EMPTY_NEW_JOB);
    else if (result.dropped !== true && result.field !== undefined) form.setError(result.field, result.sentence);
  };

  return (
    <NewRecordGroup id="jb-create" icon={Plus} title="New job" create={{ onPress: () => void create(), reason }}>
      <Row label="Name" tip={NAME_TIP} error={form.errors["name"]}>
        <Input
          type="text"
          value={form.draft.name}
          className={FIELD_CONTROL}
          aria-label="Name"
          aria-invalid={form.errors["name"] !== undefined}
          autoComplete="off"
          spellCheck={false}
          onChange={(event) => form.set({ name: event.target.value })}
          onKeyDown={(event) => {
            if (event.key === "Enter") void create();
          }}
        />
      </Row>
      <Row label="Type" tip={TYPE_FIXED_TIP}>
        <Input type="text" value={CATALOG_TYPE} readOnly className={`${FIELD_CONTROL} text-faint`} aria-label="Type" />
      </Row>
      <CatalogRows
        scope={form.draft.scope}
        kind={form.draft.kind}
        pages={form.draft.pages}
        errors={form.errors}
        onChange={form.set}
      />
      <Row label="Enabled" tip={ENABLED_TIP} error={form.errors["enabled"]}>
        <Toggle checked={form.draft.enabled} aria-label="Enabled" onChange={(enabled) => form.set({ enabled })} />
      </Row>
      <JobScheduleRows
        value={form.draft.schedule}
        error={form.errors["schedule"]}
        onChange={(schedule) => form.set({ schedule })}
      />
    </NewRecordGroup>
  );
}
